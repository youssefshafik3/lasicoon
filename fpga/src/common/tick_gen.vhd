LIBRARY IEEE;
USE IEEE.std_logic_1164.ALL;
USE IEEE.numeric_std.ALL;

ENTITY tick_gen IS
GENERIC (CLK_FREQ : INTEGER := WORK.game_pkg.CLK_FREQ);
PORT(clk,rst_n : IN STD_LOGIC;
tick_1ms, tick_1s : OUT STD_LOGIC);
END tick_gen;

ARCHITECTURE tick_gen_beh OF tick_gen IS
CONSTANT CLK_PER_MS : INTEGER := CLK_FREQ / 1000;
CONSTANT CLK_PER_S : INTEGER := CLK_FREQ;
SIGNAL CLK_PER_MS_COUNTER : INTEGER RANGE 0 TO CLK_PER_MS - 1 := 0;
SIGNAL CLK_PER_S_COUNTER : INTEGER RANGE 0 TO CLK_PER_S - 1 := 0;
BEGIN
PROCESS(clk)
BEGIN
IF clk'EVENT AND clk = '1' THEN
tick_1ms <= '0';
tick_1s <= '0';
IF rst_n = '0' THEN
CLK_PER_MS_COUNTER <= 0;
CLK_PER_S_COUNTER <= 0;
ELSE
IF CLK_PER_MS_COUNTER = CLK_PER_MS - 1 THEN
tick_1ms <= '1';
CLK_PER_MS_COUNTER <= 0;
ELSE
CLK_PER_MS_COUNTER <= CLK_PER_MS_COUNTER + 1;
END IF;

IF CLK_PER_S_COUNTER = CLK_PER_S - 1 THEN
tick_1s <= '1';
CLK_PER_S_COUNTER <= 0;
ELSE
CLK_PER_S_COUNTER <= CLK_PER_S_COUNTER + 1;
END IF;
END IF;
END IF;
END PROCESS;
END tick_gen_beh;